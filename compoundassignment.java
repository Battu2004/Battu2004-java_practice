class compoundassignment 
{
	public static void main(String[] args) 
	{
		int a=34;
		int b=12;
		int c=25;
		System.out.println(a+=b);
		System.out.println(a-=b);
		System.out.println(a*=b);
		System.out.println(a/=b);
		System.out.println(b+=c);
		System.out.println(a*=c);
		System.out.println(c%=10);
		System.out.println(b*=a);

	}
}
